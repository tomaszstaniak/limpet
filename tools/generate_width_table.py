#!/usr/bin/env python3
"""Generate the locale-independent M2b width table from pinned Unicode 17.0 data."""
import argparse
import hashlib
from pathlib import Path

SOURCES = (
    ("EastAsianWidth.txt", "ea7ce50f3444a050333448dffef1cadd9325af55cbb764b4a2280faf52170a33", {"W", "F"}),
    ("emoji-data.txt", "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b", {"Emoji_Presentation"}),
)


def ranges(text, properties):
    result = []
    for line in text.splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        span, prop = (field.strip() for field in body.split(";"))
        if prop not in properties:
            continue
        bounds = span.split("..")
        first, last = int(bounds[0], 16), int(bounds[-1], 16)
        if not 0 <= first <= last <= 0x10FFFF:
            raise ValueError("invalid Unicode range")
        result.append((first, last))
    return result


def merge(items):
    result = []
    for first, last in sorted(items):
        if result and first <= result[-1][1] + 1:
            result[-1] = (result[-1][0], max(result[-1][1], last))
        else:
            result.append((first, last))
    return result


def generate(directory):
    items = []
    for name, digest, properties in SOURCES:
        raw = (directory / name).read_bytes()
        if hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError("Unicode source checksum mismatch: " + name)
        items.extend(ranges(raw.decode("utf-8"), properties))
    lines = ["/* Generated by tools/generate_width_table.py; Unicode 17.0.0.",
             " * EAW W/F union Emoji_Presentation. See data/unicode-17.0/LICENSE.txt.",
             " * Unicode data copyright Unicode, Inc. Distributed under Unicode-3.0. */",
             "static const struct WidthRange { uint32_t first, last; } wide_ranges[] = {"]
    lines += [f"    {{0x{first:X}, 0x{last:X}}}," for first, last in merge(items)]
    return "\n".join(lines + ["};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    text = generate(args.data)
    if not args.output.exists() or args.output.read_text() != text:
        args.output.write_text(text, encoding="ascii")
