static inline unsigned eza_icon_features(const XFontGlyph *(*glyph)(uint32_t),
                                        unsigned (*width)(uint32_t),unsigned cell)
{
    unsigned i;
    if(!cell) return 0;
    for(i=0;i<sizeof eza_icon_scalars/sizeof eza_icon_scalars[0];++i) {
        const XFontGlyph *g=glyph(eza_icon_scalars[i]);
        if(!g || g->status!=XFONT_OK || !g->index || width(eza_icon_scalars[i])!=1 ||
           g->advance!=(int)(cell*64) || g->left<0 || g->top<0 ||
           (unsigned)g->left+g->width>cell) return 0;
    }
    return XTY_FEATURE_NERD_ICONS_EZA|XTY_FEATURE_ICON_WIDTH_ONE;
}
